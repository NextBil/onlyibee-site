#!/usr/bin/env python3
"""
MAKE SHARE PAGES — one tiny static page per record, so a shared link previews
with that record's own cover and title.

WHY THIS HAS TO EXIST
A link preview is built by a crawler (iMessage, WhatsApp, Instagram, Discord,
Twitter, Slack). Crawlers do NOT run JavaScript. They fetch the URL, read the
<meta property="og:*"> tags in the raw HTML, and leave. So /?s=<slug> can never
preview per song, no matter what the page does once it loads — every share of
every record would show the same generic card.

The fix is one real file per record, each carrying its own og:title and
og:image. That is what this writes:

    /s/<slug>/index.html      e.g.  onlyibee.com/s/np-27-celui-qu-elle-veut

Each file is ~2KB: the meta tags for the crawler, and an instant redirect to
/?s=<slug> for a human, so the listener still lands in the shell with the
record cued and the radio intact. The old /?s= links keep working untouched —
nothing already shared goes dead.

WHEN TO RUN IT
After adding records (a new songs-extra.js from IBEE STUDIO) or renaming one:

    python3 tools/make-share-pages.py

It rewrites the whole /s/ folder from the current song list, prints what it
did, and is safe to run as often as you like. It reads the catalogue from
assets/player.js (ALBUMS + the built-in SONGS) and assets/songs-extra.js, so
there is no second list to keep in sync.
"""
import json, os, re, sys, shutil, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://onlyibee.com"
OUT  = os.path.join(ROOT, "s")

def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()

# ---- albums: id -> {name, cover} straight out of player.js -------------------
def albums():
    js = read(os.path.join(ROOT, "assets", "player.js"))
    blk = js[js.index("var ALBUMS = {"): js.index("function album(id)")]
    out = {}
    for m in re.finditer(r'(\w+)\s*:\s*\{(.*?)\}\s*,?\s*(?=\w+\s*:\s*\{|\Z)', blk, re.S):
        aid, body = m.group(1), m.group(2)
        n = re.search(r'name\s*:\s*"([^"]*)"', body)
        c = re.search(r'cover\s*:\s*ROOT\s*\+\s*"([^"]*)"', body)
        if n:
            out[aid] = {"name": n.group(1), "cover": c.group(1) if c else ""}
    return out

# ---- every record: built-in SONGS + songs-extra ------------------------------
def songs():
    js = read(os.path.join(ROOT, "assets", "player.js"))
    blk = js[js.index("var SONGS = ["): js.index("];", js.index("var SONGS = ["))]
    out = []
    for m in re.finditer(r'\{f\s*:\s*"([^"]+)".*?n\s*:\s*"([^"]+)".*?\}', blk, re.S):
        body = m.group(0)
        al = re.search(r'al\s*:\s*"([^"]+)"', body)
        cv = re.search(r'cover\s*:\s*"([^"]+)"', body)
        out.append({"f": m.group(1), "n": m.group(2),
                    "al": al.group(1) if al else "ib",
                    "cover": cv.group(1) if cv else ""})
    x = read(os.path.join(ROOT, "assets", "songs-extra.js"))
    obj = json.loads(x[x.index("=") + 1: x.rindex("};") + 1])
    have = {s["f"] for s in out}
    for s in obj.get("songs", []):
        # songs-extra wins nothing: the built-in list is authoritative, same
        # dedupe rule player.js uses
        if s.get("f") in have:
            continue
        out.append({"f": s["f"], "n": s.get("n") or s["f"],
                    "al": s.get("g") or "ib", "cover": s.get("cover", "")})
    return out

def meta():
    try:
        m = read(os.path.join(ROOT, "assets", "song-meta.js"))
        return json.loads(m[m.index("=") + 1: m.rindex("};") + 1])
    except Exception:
        return {}

PAGE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<!-- GENERATED by tools/make-share-pages.py — do not hand-edit, it is rewritten.
     A crawler reads the tags below and stops; a person is redirected to the
     real page by the script at the bottom. -->
<title>{title}</title>
<!-- Self-canonical ON PURPOSE. It used to point at /?s={slug}, and several
     scrapers (Facebook and WhatsApp among them) follow rel=canonical and read
     THAT page's tags instead — which are the generic site ones, so a correctly
     shared link still previewed as the plain homepage card. noindex keeps these
     63 redirect stubs out of search while leaving them scrapable. -->
<link rel="canonical" href="{site}/s/{slug}/">
<meta name="robots" content="noindex, follow">
<meta name="description" content="{desc}">
<meta property="og:type" content="music.song">
<meta property="og:site_name" content="ONLY IBEE">
<meta property="og:title" content="{ogtitle}">
<meta property="og:description" content="{desc}">
<meta property="og:url" content="{site}/s/{slug}/">
<meta property="og:image" content="{cover}">
<meta property="og:image:secure_url" content="{cover}">
<meta property="og:image:width" content="{cw}">
<meta property="og:image:height" content="{ch}">
<meta property="og:image:alt" content="{alt}">
<meta property="music:musician" content="{site}/">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="{ogtitle}">
<meta name="twitter:description" content="{desc}">
<meta name="twitter:image" content="{cover}">
<meta name="theme-color" content="#070707">
<link rel="icon" type="image/svg+xml" href="/assets/img/favicon.svg">
<style>html,body{{height:100%;margin:0;background:#070707;color:#b6ff00;
  font-family:'Press Start 2P',monospace;display:flex;align-items:center;
  justify-content:center;font-size:11px;letter-spacing:1px}}</style>
</head>
<body>
<p>OPENING THE RECORD_ <a href="/?s={slug}" style="color:#26e0ff">tap here</a></p>
<script>location.replace('/?s={slug}');</script>
</body>
</html>
"""

def main():
    AL, MET = albums(), meta()
    # real pixel sizes so the crawler does not have to guess (and so a square
    # cover is not reported as a 1200x630 banner it is not)
    sizes = {}
    try:
        import subprocess
        for a in AL.values():
            p = os.path.join(ROOT, a["cover"])
            if a["cover"] and os.path.exists(p):
                o = subprocess.run(["sips", "-g", "pixelWidth", "-g", "pixelHeight", p],
                                   capture_output=True, text=True).stdout
                w = re.search(r"pixelWidth:\s*(\d+)", o)
                h = re.search(r"pixelHeight:\s*(\d+)", o)
                if w and h:
                    sizes[a["cover"]] = (w.group(1), h.group(1))
    except Exception:
        pass

    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT, exist_ok=True)

    n = 0
    for s in songs():
        slug = re.sub(r"\.mp3$", "", s["f"], flags=re.I)
        alb = AL.get(s["al"], AL.get("ib", {"name": "ONLY IBEE", "cover": ""}))
        cover = s["cover"] or alb["cover"]
        cw, ch = sizes.get(cover, ("1200", "1200"))
        m = MET.get(s["f"], {})
        desc = (m.get("meaning") or m.get("vibe")
                or "A record from ONLY IBEE. Press play, read what it means, "
                   "and see where it is being heard.")
        e = lambda t: html.escape(str(t), quote=True)
        page = PAGE.format(
            site=SITE, slug=slug,
            title=e("%s — ONLY IBEE" % s["n"]),
            ogtitle=e("%s — ONLY IBEE" % s["n"]),
            desc=e(desc),
            cover=SITE + "/" + cover.lstrip("/"),
            cw=cw, ch=ch,
            alt=e("%s cover art" % alb["name"]))
        d = os.path.join(OUT, slug)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "index.html"), "w", encoding="utf-8") as f:
            f.write(page)
        n += 1

    print("wrote %d share pages into /s/" % n)
    print("share links now look like: %s/s/<slug>" % SITE)

if __name__ == "__main__":
    main()
